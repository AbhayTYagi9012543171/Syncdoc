const mongoose = require("mongoose");
const fs = require("fs/promises");
const path = require("path");
const { randomUUID } = require("crypto");

const User = require("../models/User");
const { logger } = require("../config/logger");

const MAX_NAME_LENGTH = 50;
const MAX_BIO_LENGTH = 500;
const MAX_AVATAR_BYTES = 5 * 1024 * 1024;

const AVATAR_DIR = path.resolve(
  __dirname,
  "../../uploads/profile-avatars"
);

function detectImage(buffer) {
  if (!Buffer.isBuffer(buffer)) return null;

  // JPEG
  if (
    buffer.length >= 3 &&
    buffer[0] === 0xff &&
    buffer[1] === 0xd8 &&
    buffer[2] === 0xff
  ) {
    return { ext: "jpg", mime: "image/jpeg" };
  }

  // PNG
  if (
    buffer.length >= 8 &&
    buffer.subarray(0, 8).equals(
      Buffer.from([
        0x89, 0x50, 0x4e, 0x47,
        0x0d, 0x0a, 0x1a, 0x0a,
      ])
    )
  ) {
    return { ext: "png", mime: "image/png" };
  }

  // GIF
  if (
    buffer.length >= 6 &&
    ["GIF87a", "GIF89a"].includes(
      buffer.subarray(0, 6).toString("ascii")
    )
  ) {
    return { ext: "gif", mime: "image/gif" };
  }

  // WEBP
  if (
    buffer.length >= 12 &&
    buffer.subarray(0, 4).toString("ascii") === "RIFF" &&
    buffer.subarray(8, 12).toString("ascii") === "WEBP"
  ) {
    return { ext: "webp", mime: "image/webp" };
  }

  return null;
}

function publicAvatarUrl(req, filename) {
  // Set PUBLIC_API_URL to e.g. https://app.example.com/api when running
  // behind a reverse proxy or when the API is exposed on a separate host.
  const configuredBase = String(process.env.PUBLIC_API_URL || "").trim();
  const origin = configuredBase
    ? configuredBase.replace(/\/$/, "")
    : `${req.protocol}://${req.get("host")}${String(req.baseUrl || "").replace(/\/profile$/, "")}`;

  const baseWithApi = origin.replace(/\/$/, "");
  return `${baseWithApi}/uploads/profile-avatars/${filename}`;
}

async function removeStoredAvatar(avatarUrl) {
  if (typeof avatarUrl !== "string" || !avatarUrl) return;

  try {
    const parsed = new URL(avatarUrl, "http://localhost");
    const marker = "/uploads/profile-avatars/";
    const markerIndex = parsed.pathname.lastIndexOf(marker);

    if (markerIndex < 0) return;

    const filename = path.basename(
      parsed.pathname.slice(markerIndex + marker.length)
    );

    // Only remove filenames generated by this controller.
    if (!/^[a-f0-9-]+\.(?:jpg|png|webp|gif)$/i.test(filename)) {
      return;
    }

    await fs.unlink(path.join(AVATAR_DIR, filename)).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  } catch (error) {
    logger.warn(
      "Could not remove previous profile avatar:",
      error.message
    );
  }
}

function publicProfile(user) {
  if (!user) return null;

  const value =
    typeof user.toJSON === "function"
      ? user.toJSON()
      : { ...user };

  // Never expose these fields through profile endpoints.
  delete value.password;
  delete value.activeSessions;
  delete value.resetPasswordToken;
  delete value.resetPasswordExpires;

  return value;
}

function validationError(message, field) {
  const error = new Error(message);
  error.status = 400;
  error.field = field;
  return error;
}

function validatePayload(body) {
  if (!body || typeof body !== "object" || Array.isArray(body)) {
    throw validationError("Profile changes must be a JSON object.");
  }

  const allowed = ["displayName", "bio", "avatar"];
  const keys = Object.keys(body);

  if (!keys.length || keys.some((key) => !allowed.includes(key))) {
    throw validationError(
      "Provide only displayName, bio, or avatar fields."
    );
  }

  const update = {};

  if (Object.prototype.hasOwnProperty.call(body, "displayName")) {
    if (typeof body.displayName !== "string") {
      throw validationError("Display name must be text.", "displayName");
    }

    const displayName = body.displayName.trim();

    if (
      displayName.length < 2 ||
      displayName.length > MAX_NAME_LENGTH
    ) {
      throw validationError(
        `Display name must be between 2 and ${MAX_NAME_LENGTH} characters.`,
        "displayName"
      );
    }

    update.displayName = displayName;
  }

  if (Object.prototype.hasOwnProperty.call(body, "bio")) {
    if (typeof body.bio !== "string") {
      throw validationError("Bio must be text.", "bio");
    }

    const bio = body.bio.trim();

    if (bio.length > MAX_BIO_LENGTH) {
      throw validationError(
        `Bio cannot exceed ${MAX_BIO_LENGTH} characters.`,
        "bio"
      );
    }

    update.bio = bio;
  }

  if (Object.prototype.hasOwnProperty.call(body, "avatar")) {
    if (body.avatar === null || body.avatar === "") {
      update.avatar = null;
    } else {
      if (
        typeof body.avatar !== "string" ||
        body.avatar.length > 2048
      ) {
        throw validationError(
          "Avatar must be a valid HTTPS image URL.",
          "avatar"
        );
      }

      let parsed;

      try {
        parsed = new URL(body.avatar);
      } catch {
        throw validationError(
          "Avatar must be a valid HTTPS image URL.",
          "avatar"
        );
      }

      if (parsed.protocol !== "https:") {
        throw validationError(
          "Avatar URLs must use HTTPS.",
          "avatar"
        );
      }

      update.avatar = parsed.toString();
    }
  }

  return update;
}

function getAuthenticatedUserId(req) {
  return req.user?._id || req.userId || null;
}

function isValidAuthenticatedUserId(userId) {
  return Boolean(userId && mongoose.isValidObjectId(userId));
}

const ProfileController = {
  async getMe(req, res, next) {
    try {
      const userId = getAuthenticatedUserId(req);

      if (!isValidAuthenticatedUserId(userId)) {
        return res.status(401).json({
          success: false,
          message: "Authentication required.",
        });
      }

      const user = await User.findOne({
        _id: userId,
        deletedAt: null,
      });

      if (!user) {
        return res.status(404).json({
          success: false,
          message: "Profile not found.",
        });
      }

      return res.json({
        success: true,
        data: { user: publicProfile(user) },
      });
    } catch (error) {
      logger.error("Get current profile failed:", error);
      return next(error);
    }
  },

  async updateMe(req, res, next) {
    try {
      const userId = getAuthenticatedUserId(req);

      if (!isValidAuthenticatedUserId(userId)) {
        return res.status(401).json({
          success: false,
          message: "Authentication required.",
        });
      }

      const update = validatePayload(req.body);

      const user = await User.findOneAndUpdate(
        { _id: userId, deletedAt: null },
        { $set: { ...update, updatedAt: new Date() } },
        { new: true, runValidators: true, context: "query" }
      );

      if (!user) {
        return res.status(404).json({
          success: false,
          message: "Profile not found.",
        });
      }

      return res.json({
        success: true,
        message: "Profile updated successfully.",
        data: { user: publicProfile(user) },
      });
    } catch (error) {
      if (
        error.status === 400 ||
        error.name === "ValidationError" ||
        error.name === "CastError"
      ) {
        return res.status(400).json({
          success: false,
          message: error.message || "Invalid profile data.",
          field: error.field,
        });
      }

      logger.error("Update current profile failed:", error);
      return next(error);
    }
  },

  async uploadAvatar(req, res, next) {
    let storedPath = null;

    try {
      const userId = getAuthenticatedUserId(req);

      if (!isValidAuthenticatedUserId(userId)) {
        return res.status(401).json({
          success: false,
          message: "Authentication required.",
        });
      }

      if (!req.file || !req.file.buffer) {
        return res.status(400).json({
          success: false,
          message: "Choose an image file to upload.",
        });
      }

      if (req.file.size > MAX_AVATAR_BYTES) {
        return res.status(413).json({
          success: false,
          message: "Photo must be 5 MB or smaller.",
        });
      }

      const image = detectImage(req.file.buffer);

      if (!image) {
        return res.status(415).json({
          success: false,
          message:
            "The file contents are not a supported image. Use JPG, PNG, WEBP, or GIF.",
        });
      }

      const user = await User.findOne({
        _id: userId,
        deletedAt: null,
      });

      if (!user) {
        return res.status(404).json({
          success: false,
          message: "Profile not found.",
        });
      }

      await fs.mkdir(AVATAR_DIR, { recursive: true });

      const filename = `${randomUUID()}.${image.ext}`;
      storedPath = path.join(AVATAR_DIR, filename);

      await fs.writeFile(storedPath, req.file.buffer, {
        flag: "wx",
        mode: 0o644,
      });

      const previousAvatar = user.avatar;

      user.avatar = publicAvatarUrl(req, filename);
      user.updatedAt = new Date();

      await user.save();

      // Clean up only after the new avatar has been saved.
      await removeStoredAvatar(previousAvatar);

      return res.json({
        success: true,
        message: "Profile photo uploaded successfully.",
        data: {
          user: publicProfile(user),
          avatar: user.avatar,
        },
      });
    } catch (error) {
      if (storedPath) {
        await fs.unlink(storedPath).catch(() => {});
      }

      if (
        error.name === "ValidationError" ||
        error.name === "CastError"
      ) {
        return res.status(400).json({
          success: false,
          message: error.message || "Invalid profile data.",
        });
      }

      logger.error("Upload profile avatar failed:", error);
      return next(error);
    }
  },

  async removeAvatar(req, res, next) {
    try {
      const userId = getAuthenticatedUserId(req);

      if (!isValidAuthenticatedUserId(userId)) {
        return res.status(401).json({
          success: false,
          message: "Authentication required.",
        });
      }

      const user = await User.findOne({
        _id: userId,
        deletedAt: null,
      });

      if (!user) {
        return res.status(404).json({
          success: false,
          message: "Profile not found.",
        });
      }

      const previousAvatar = user.avatar;

      user.avatar = null;
      user.updatedAt = new Date();

      await user.save();
      await removeStoredAvatar(previousAvatar);

      return res.json({
        success: true,
        message: "Profile photo removed.",
        data: {
          user: publicProfile(user),
          avatar: null,
        },
      });
    } catch (error) {
      logger.error("Remove profile avatar failed:", error);
      return next(error);
    }
  },
};

module.exports = ProfileController;